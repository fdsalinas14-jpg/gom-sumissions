export function toEnglish(fr) {
  if (!fr) return '';
  return String(fr).split('\n').map((line) => {
    const m = line.match(/^(#\s+|•\s+)?(.*)$/);
    let s = m[2];
    for (const [re, to] of R) s = s.replace(re, to);
    s = s.replace('CEQ and manufacturer guidelines standards in Québec', 'CEQ standards in Québec and manufacturer guidelines');
    return (m[1] || '') + s.replace(/\s+:/g, ':');
  }).join('\n');
}

