// Prueba de navegador: sub-sección Multi-split, comisión del vendedor, vista previa del PDF y firma del cliente.
// Uso: node test/e2e-sign.cjs   (E2E_SHOTS=carpeta para guardar capturas)
const { chromium } = require('playwright');
const assert = (c, msg) => { if (!c) throw new Error(msg); };
const { spawn } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const OUT = (process.env.E2E_SHOTS || fs.mkdtempSync(path.join(os.tmpdir(), 'e2e-'))) + '/sign-';
const srv = spawn(process.execPath, [path.join(__dirname, 'serve-e2e.js')], { env: { ...process.env, PORT: '3115' }, stdio: 'ignore' });
const B = 'http://127.0.0.1:3115/';
(async () => {
  await new Promise((r) => setTimeout(r, 3000));
  const browser = await chromium.launch();
  const errors = [];
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const p = await ctx.newPage();
  p.on('pageerror', (e) => errors.push('ERR ' + e.message));
  await p.goto(B);
  await p.fill('input[autocomplete=username]', 'nico'); await p.fill('input[type=password]', 'clave-nico'); await p.click('button[type=submit]');
  await p.waitForSelector('.stats');
  await p.click('text=Faire une soumission'); await p.waitForSelector('.step-head');
  await p.fill('input[type=search]', 'Marie'); await p.waitForSelector('button.pick'); await p.click('button.pick');
  await p.waitForSelector('.tile');
  await p.screenshot({ path: OUT + '1-cats.png', fullPage: true });
  await p.click('.tile:has-text("Multizone")');
  await p.waitForSelector('.crumb');
  await p.screenshot({ path: OUT + '2-sub.png', fullPage: true });
  await p.click('.tile:has-text("Têtes intérieures")');
  await p.click('.tile:has-text("Kinghome")');
  await p.waitForTimeout(200);
  await p.screenshot({ path: OUT + '3-caps.png', fullPage: true });
  await p.click('.tiles.caps .tile >> nth=0');
  await p.click('button.pick >> nth=0');
  await p.click('.dock .btn.hi');
  await p.waitForSelector('.comm-box');
  await p.fill('input[id^=price-]', '9000');
  await p.fill('[data-comm-in]', '900');
  await p.waitForTimeout(200);
  assert((await p.textContent('[data-client]')).replace(/\s/g, '').includes('9900,00'), 'precio + comisión');
  await p.screenshot({ path: OUT + '4-step3.png', fullPage: false });
  await p.click('.dock .btn.hi');
  await p.waitForSelector('.sum-line');
  await p.screenshot({ path: OUT + '5-step4.png', fullPage: true });
  const [resp] = await Promise.all([p.waitForResponse((r) => r.url().includes('preview=1')), p.click('text=Voir le PDF avant')]);
  assert(resp.status() === 200 && resp.headers()['content-type'] === 'application/pdf', 'vista previa PDF');
  await p.waitForTimeout(500);
  for (const pg of ctx.pages()) if (pg !== p) await pg.close().catch(() => {});
  await p.click('text=Envoyer au client');
  await p.waitForSelector('.actions');
  const id = p.url().match(/q\/(\d+)/)[1];
  const sign = await p.evaluate(async (id) => (await (await fetch(`/api/estimates?id=${id}`)).json()).sign, id);
  assert(/\/signer\?id=\d+&k=/.test(sign), 'enlace de firma');
  // Cliente en su teléfono
  const c = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const q = await c.newPage();
  q.on('pageerror', (e) => errors.push('C-ERR ' + e.message));
  await q.goto(sign.replace('http://127.0.0.1:3111', 'http://127.0.0.1:3115').replace(/^https?:\/\/[^/]+/, 'http://127.0.0.1:3115'));
  await q.waitForSelector('.sig-pad');
  await q.screenshot({ path: OUT + '6-client.png', fullPage: true });
  await (await q.$('.sig-pad')).scrollIntoViewIfNeeded(); const box = await (await q.$('.sig-pad')).boundingBox();
  await q.mouse.move(box.x + 20, box.y + 100); await q.mouse.down();
  for (let i = 0; i < 40; i++) await q.mouse.move(box.x + 20 + i * 7, box.y + 90 + Math.sin(i / 3) * 40);
  await q.mouse.up();
  await q.check('#sig-agree');
  await q.click('text=Signer et accepter');
  await q.waitForSelector('.signed-box');
  await q.screenshot({ path: OUT + '7-signed.png', fullPage: false });
  const pdfHref = await q.getAttribute('a.btn.primary', 'href');
  const pdf = await c.request.get(pdfHref.replace(/^https?:\/\/[^/]+/, 'http://127.0.0.1:3115'));
  fs.writeFileSync(OUT + 'signed.pdf', await pdf.body());
  await p.reload(); await p.waitForSelector('.signed-box');
  await p.screenshot({ path: OUT + '8-admin.png', fullPage: false });
  assert((await pdf.body()).length > 1000, 'PDF firmado');
  assert(!errors.length, errors.join(' | '));
  console.log('E2E firma OK — capturas en', OUT);
  await browser.close(); srv.kill();
})().catch((e) => { console.error(e); srv.kill(); process.exit(1); });
