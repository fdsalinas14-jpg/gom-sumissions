// Prueba de navegador v3: admin importa el catálogo, hace y envía una soumission; vendedor en teléfono.
// Uso: node test/e2e.js   (E2E_SHOTS=carpeta para guardar capturas)
const { chromium } = require('playwright');
const { spawn } = require('node:child_process');
const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');
const OUT = (process.env.E2E_SHOTS || fs.mkdtempSync(path.join(os.tmpdir(), 'e2e-'))) + '/';
const PORT = 3112;
const B = `http://127.0.0.1:${PORT}/`;
const srv = spawn(process.execPath, [path.join(__dirname, 'serve-e2e.js')], { env: { ...process.env, PORT: String(PORT) }, stdio: 'ignore' });
const assert = (c, msg) => { if (!c) throw new Error(msg); };
(async () => {
  await new Promise((r) => setTimeout(r, 2500));
  const browser = await chromium.launch();
  const errors = [];
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const p = await ctx.newPage();
  p.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  p.on('pageerror', (e) => errors.push('PAGEERR ' + e.message));
  const shot = (n) => p.screenshot({ path: OUT + n + '.png', fullPage: true });
  await p.goto(B);
  await p.fill('input[autocomplete=username]', 'nico');
  await p.fill('input[type=password]', 'clave-nico');
  await p.click('button[type=submit]');
  await p.waitForSelector('.stats .stat');
  await shot('01-home');
  await p.goto(B + '#/catalog');
  await p.waitForSelector('a.quote');
  assert(!(await p.$('text=Importer')), 'no hay botón de importación');
  await shot('02-catalog');
  await p.click('a.seg:nth-child(3)');
  await p.waitForSelector('details.card.fold');
  await p.click('details.card.fold >> nth=0 >> summary');
  await shot('03-categories');
  await p.click('a.seg:nth-child(2)');
  await p.waitForSelector('a.quote');
  await shot('04-options');
  await p.click('a.seg:nth-child(1)');
  await p.waitForSelector('a.quote');
  await p.click('a.quote >> nth=0');
  await p.waitForSelector('.desc-box');
  await shot('05-product');
  // New quote
  await p.goto(B + '#/home');
  await p.click('text=Faire une soumission');
  await p.waitForSelector('.step-head');
  await p.fill('input[type=search]', 'Marie');
  await p.waitForSelector('button.pick').catch(async (e) => { await shot('ERR-search'); throw e; });
  await p.click('button.pick');
  await p.waitForSelector('.tile');
  await shot('06-step2-cats');
  await p.click('.tile >> nth=0');
  await p.waitForSelector('.crumb');
  await shot('07-step2-brands');
  await p.click('.tile >> nth=0');
  await p.waitForTimeout(200);
  if (await p.$('.tiles.caps')) { await shot('08-step2-caps'); await p.click('.tiles.caps .tile >> nth=0'); }
  await p.waitForSelector('button.pick');
  await shot('09-step2-models');
  await p.click('button.pick >> nth=0');
  await p.waitForSelector('.eq-chosen');
  await p.click('.dock .btn.hi');
  await p.waitForSelector('.client-price');
  const priceIn = await p.$('input[id^=price-]');
  await priceIn.fill('');
  await priceIn.type('15000');
  await p.waitForTimeout(200);
  console.log('CLIENT PRICE:', await p.textContent('[data-client]'), 'TOTAL:', await p.textContent('[data-total]'));
  await shot('10-step3');
  await p.click('.dock .btn.hi');
  await p.waitForSelector('.final-btns');
  await shot('11-step4');
  await p.click('.final-btns .btn.hi');
  await p.waitForSelector('.actions');
  const fl = await p.textContent('.flash'); console.log('FLASH:', fl); assert(/Courriel/.test(fl), 'send flash');
  await shot('12-detail-sent');
  await p.click('text=Marquer acceptée');
  await p.waitForSelector('.flash');
  await p.click('text=Marquer payée');
  await p.waitForSelector('.flash');
  await shot('13-detail-paid');
  await p.goto(B + '#/reviews');
  await p.waitForSelector('.review-card');
  await shot('14-reviews');
  await p.goto(B + '#/home');
  await p.waitForSelector('a.quote');
  await shot('15-home-after');
  await p.goto(B + '#/settings');
  await p.waitForSelector('details.card.fold');
  await shot('16-settings');
  await p.goto(B + '#/sellers');
  await p.waitForSelector('a.quote');
  await shot('17-sellers');
  await p.goto(B + '#/history');
  await p.waitForSelector('.events');
  await shot('18-history');
  // PDF
  const pdfHref = await (await p.goto(B + '#/home'), p.waitForSelector('a.quote'), p.click('a.quote'), p.waitForSelector('a.btn.primary'), p.getAttribute('a.btn.primary', 'href'));
  const r = await ctx.request.get(pdfHref);
  assert(r.status() === 200 && r.headers()['content-type'] === 'application/pdf', 'pdf');
  require('fs').writeFileSync(OUT + 'quote.pdf', await r.body());

  // Mobile seller
  const m = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const q = await m.newPage();
  q.on('pageerror', (e) => errors.push('M-PAGEERR ' + e.message));
  q.on('console', (x) => { if (x.type() === 'error') errors.push('M ' + x.text()); });
  await q.goto(B);
  await q.fill('input[autocomplete=username]', 'marie');
  await q.fill('input[type=password]', 'clave-marie');
  await q.click('button[type=submit]');
  await q.waitForSelector('.stats');
  await q.screenshot({ path: OUT + '20-m-home.png', fullPage: true });
  await q.click('text=Faire une soumission');
  await q.waitForSelector('.step-head');
  await q.fill('input[type=search]', 'Marie');
  await q.waitForSelector('button.pick'); await q.click('button.pick');
  await q.waitForSelector('.tile');
  await q.screenshot({ path: OUT + '21-m-step2.png', fullPage: true });
  await q.click('.tile >> nth=0'); await q.waitForSelector('.crumb'); await q.click('.tile >> nth=0');
  await q.waitForTimeout(200);
  if (await q.$('.tiles.caps')) await q.click('.tiles.caps .tile >> nth=0');
  await q.waitForSelector('button.pick'); await q.click('button.pick >> nth=0');
  await q.click('.dock .btn.hi');
  await q.waitForSelector('.client-price');
  await q.fill('input[id^=price-]', '15000');
  await q.screenshot({ path: OUT + '22-m-step3.png', fullPage: true });
  await q.click('.dock .btn.hi');
  await q.waitForSelector('.final-btns');
  await q.screenshot({ path: OUT + '23-m-step4.png', fullPage: true });
  await q.click('text=Enregistrer le brouillon');
  await q.waitForSelector('.actions');
  await q.screenshot({ path: OUT + '24-m-detail.png', fullPage: true });
  const real = errors.filter((e) => !/TUNNEL|401|fonts|storage.googleapis/.test(e));
  assert(!real.length, 'errores en la consola: ' + real.join(' | '));
  await browser.close();
  srv.kill();
  console.log('E2E OK — capturas en', OUT);
})().catch((e) => { console.error('FAIL', e); srv.kill(); process.exit(1); });
